// Единая точка правды про «стоп»: кому бот НЕ должен писать сам.
//
// Три независимых уровня защиты (любой из них запрещает проактивную отправку):
//   1. Глобальный рубильник FOLLOWUPS_ENABLED=0 — бот вообще перестаёт
//      инициировать переписку (реактивные ответы на входящие остаются).
//   2. Стоп-лист FOLLOWUP_BLOCKLIST — номера, которые бот не трогает совсем
//      (поставщики, партнёры, сотрудники, свои же номера).
//   3. Стоп самого клиента: он написал «не пишите» / «отписаться» / «стоп»
//      → статус диалога становится stopped и БОЛЬШЕ НЕ СБРАСЫВАЕТСЯ
//      автоматически (см. handlers/followup.js).
//
// Все функции чистые (кроме чтения process.env по умолчанию) — тестируются
// без сети и БД.

// Нормализация: нижний регистр, ё→е, любая пунктуация/эмодзи → пробел.
// Результат обрамлён пробелами, чтобы искать фразы по границам слов
// (в JS \b не работает с кириллицей).
export function normalizeText(text) {
  const body = String(text ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9]+/g, " ")
    .trim();
  return ` ${body} `;
}

// Фразы отказа. Пишутся уже нормализованными (нижний регистр, слова через
// один пробел) и матчатся строго по границам слов.
export const STOP_PHRASES = [
  // отказ от предложения
  "не нужно", "ненужно", "не надо", "не требуется", "не хочу",
  "не интересно", "неинтересно", "не интересует", "неинтересует",
  "не актуально", "неактуально", "передумал", "передумала",
  "откажусь", "отказываюсь",
  // прямой запрет писать/звонить
  "стоп", "stop", "не пишите", "не пиши", "больше не пишите", "хватит писать",
  "перестаньте писать", "перестань писать", "прекратите", "прекрати",
  "перестаньте", "не беспокойте", "не беспокоить", "не тревожьте",
  "не звоните", "не звони", "оставьте меня в покое", "отстаньте",
  // отписка / удаление из базы
  "отписаться", "отписка", "отпишите", "отпишись", "отписываюсь",
  "unsubscribe", "удалите мой номер", "удалите номер", "уберите мой номер",
  "уберите номер", "удалите из базы", "уберите из базы", "удалите меня",
  "уберите меня",
  // жалобы
  "это спам", "ваш спам", "хватит спама", "спамите", "жалоба", "пожалуюсь",
  "в чс", "черный список", "заблокирую"
];

// true — клиент просит больше не писать (или отказывается от предложения).
export function isStopRequest(text, phrases = STOP_PHRASES) {
  const norm = normalizeText(text);
  return phrases.some(p => norm.includes(` ${p} `));
}

// Ключ номера для сравнения: только цифры, последние 10 (как phoneLast10
// в qualify.js). Для коротких номеров — все цифры целиком.
export function digitsKey(chatId) {
  const digits = String(chatId ?? "").split("@")[0].replace(/\D/g, "");
  if (!digits) return null;
  return digits.length > 10 ? digits.slice(-10) : digits;
}

// "77011234567, +7 702 000-00-00" → Set ключей. Разделители — запятая,
// точка с запятой и перевод строки (но НЕ пробел: он часто внутри номера).
export function parseBlocklist(raw) {
  return new Set(
    String(raw ?? "")
      .split(/[,;\n]+/)
      .map(digitsKey)
      .filter(Boolean)
  );
}

// true — номер в стоп-листе, бот не пишет ему ни сам, ни в ответ.
export function isBlocked(chatId, raw = process.env.FOLLOWUP_BLOCKLIST) {
  const key = digitsKey(chatId);
  if (!key) return false;
  return parseBlocklist(raw).has(key);
}

// Глобальный рубильник проактивных сообщений. По умолчанию включено;
// FOLLOWUPS_ENABLED=0 (false/no/off) — бот молчит, пока к нему не написали.
export function followupsEnabled(env = process.env) {
  const v = String(env.FOLLOWUPS_ENABLED ?? "1").trim().toLowerCase();
  return !(v === "0" || v === "false" || v === "no" || v === "off");
}
